"""One-time local step: download JetBrains Mono, subset it to the handful of
characters these graphics actually draw, and write the result out as base64
strings in `fonts_inline.py`.

Run this once (or again if you change the character set). The daily GitHub
Action never runs it -- it only imports the generated module, which is pure
stdlib. That is why `generate_stats.py` needs no pip install step.

    python scripts/make_fonts.py

Requires: fonttools, brotli  (local only)
JetBrains Mono is SIL Open Font License 1.1.
"""

import base64
import pathlib
import urllib.request

HERE = pathlib.Path(__file__).resolve().parent
CACHE = HERE / "fonts"
OUT = HERE / "fonts_inline.py"

# Weight -> source. fontsource serves clean, already-woff2 latin subsets.
SOURCES = {
    400: "https://unpkg.com/@fontsource/jetbrains-mono/files/jetbrains-mono-latin-400-normal.woff2",
    600: "https://unpkg.com/@fontsource/jetbrains-mono/files/jetbrains-mono-latin-600-normal.woff2",
}

# Every character the SVGs can draw. Keep this tight -- it is the whole reason
# the embedded font is ~5KB instead of ~90KB.
GLYPHS = (
    "abcdefghijklmnopqrstuvwxyz"
    "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    "0123456789"
    " .,:;+-/%()[]#@*<>'\"_=|"
    "·"  # middot, used in the link row
    "–"  # en dash, used in date ranges
    "—"  # em dash
)


def fetch(url: str, dest: pathlib.Path) -> bytes:
    if dest.exists():
        return dest.read_bytes()
    dest.parent.mkdir(parents=True, exist_ok=True)
    req = urllib.request.Request(url, headers={"User-Agent": "profile-font-fetch"})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = r.read()
    dest.write_bytes(data)
    return data


def subset(src: pathlib.Path, dest: pathlib.Path) -> bytes:
    from fontTools import subset as fts

    opts = fts.Options()
    opts.flavor = "woff2"
    opts.desubroutinize = True
    opts.layout_features = []          # no kerning/ligatures needed in mono
    opts.name_IDs = []
    opts.notdef_outline = False
    opts.recalc_bounds = True
    opts.drop_tables += ["GSUB", "GPOS", "GDEF", "DSIG"]

    font = fts.load_font(str(src), opts)
    subsetter = fts.Subsetter(options=opts)
    subsetter.populate(text=GLYPHS)
    subsetter.subset(font)
    fts.save_font(font, str(dest), opts)
    font.close()
    return dest.read_bytes()


def main() -> None:
    lines = [
        '"""Generated by scripts/make_fonts.py -- do not edit by hand.',
        "",
        "Base64 WOFF2 subsets of JetBrains Mono (SIL Open Font License 1.1),",
        "cut down to only the characters the profile graphics draw.",
        '"""',
        "",
        "FONTS = {",
    ]

    for weight, url in SOURCES.items():
        raw = fetch(url, CACHE / f"jbmono-{weight}.woff2")
        cut = subset(CACHE / f"jbmono-{weight}.woff2", CACHE / f"jbmono-{weight}.sub.woff2")
        b64 = base64.b64encode(cut).decode("ascii")
        pct = 100 - round(len(cut) / len(raw) * 100)
        print(f"  weight {weight}: {len(raw):>7,}B -> {len(cut):>6,}B  ({pct}% smaller)")
        lines.append(f"    {weight}: (")
        for i in range(0, len(b64), 100):
            lines.append(f'        "{b64[i:i + 100]}"')
        lines.append("    ),")

    lines += ["}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nwrote {OUT.relative_to(HERE.parent)}  ({OUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
